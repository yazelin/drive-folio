import * as THREE from 'three'
import { FontLoader } from 'three/examples/jsm/loaders/FontLoader.js'
import { TextGeometry } from 'three/examples/jsm/geometries/TextGeometry.js'
import fontData from 'three/examples/fonts/helvetiker_bold.typeface.json'

// 原作地上的「BRUNO SIMON」是一個字母一個 Blender 模型,只有那幾個字母可用。
// 這裡改成用 TextGeometry 即時產生字,再照原作的命名規則包成 base / collision:
// base 裡的網格叫 shadeWhite(Objects 依名字套 matcap),collision 裡放 center 與 cube(Physics 依名字與 scale 建碰撞)。
const FONT = new FontLoader().parse(fontData)

function makeWord(text, { x, y, height, depth, standing })
{
    const geometry = new TextGeometry(text, { font: FONT, size: 1, depth: 1, curveSegments: 6, bevelEnabled: false })
    geometry.computeBoundingBox()
    const box = geometry.boundingBox
    const w = box.max.x - box.min.x
    const h = box.max.y - box.min.y
    const k = height / h
    // 置中、縮放:寬高照字型比例,厚度固定 depth
    geometry.translate(- box.min.x - w / 2, - box.min.y - h / 2, - 0.5)
    geometry.scale(k, k, depth)
    const width = w * k

    const mesh = new THREE.Mesh(geometry)
    mesh.name = 'shadeWhite'
    const center = new THREE.Object3D()
    center.name = 'center'
    const cube = new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1))
    cube.name = 'cube'

    if(standing)
    {
        // 站著的字:文字面朝 -y、底部貼地(z 軸朝上)
        mesh.rotation.x = Math.PI / 2
        mesh.position.set(x, y, height / 2)
        cube.scale.set(width, depth, height)
    }
    else
    {
        // 平躺在地上的字
        mesh.position.set(x, y, depth / 2)
        cube.scale.set(width, height, depth)
    }
    center.position.copy(mesh.position)
    cube.position.copy(mesh.position)

    const base = new THREE.Object3D(); base.add(mesh)
    const collision = new THREE.Object3D(); collision.add(center, cube)
    return { base, collision, width }
}

